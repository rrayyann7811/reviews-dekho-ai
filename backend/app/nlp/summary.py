"""Grounded summary: sentences built only from computed numbers and real
review snippets. Nothing here is generated by a language model, so it
cannot invent features or opinions. An optional LLM layer can be added
later on top of the same inputs.
"""
MIN_REVIEWS_FOR_SUMMARY = 5


def _aspect_line(row: dict, kind: str) -> dict:
    count = row[kind]
    example = row["examplePositive"] if kind == "positive" else row["exampleNegative"]
    return {
        "aspect": row["aspect"],
        "mentions": row["mentions"],
        "count": count,
        "percent": round(100 * count / row["mentions"]),
        "positive": row["positive"],
        "neutral": row["neutral"],
        "negative": row["negative"],
        "example": example,
    }


def _language_note(stats: dict) -> list[str]:
    skipped = (stats.get("notAnalysed") or {}).get("languageNotSupported", 0)
    if not skipped:
        return []
    noun, verb = ("review", "is") if skipped == 1 else ("reviews", "are")
    return [f"{skipped} {noun} {verb} not in English (for example Hindi or Hinglish), so their sentiment wasn’t "
            "analysed. They are left out of the percentages; their star ratings still count."]


def build_summary(stats: dict, aspects: list[dict]) -> dict:
    total = stats.get("analysedReviews", stats["totalReviews"])
    if total < MIN_REVIEWS_FOR_SUMMARY:
        first = ("No review could be analysed, so there is no summary." if total == 0 else
                 f"Only {total} review(s) could be analysed. At least {MIN_REVIEWS_FOR_SUMMARY} are needed for a "
                 "meaningful summary.")
        return {"overview": None, "strengths": [], "complaints": [], "mixed": [], "notes": [first, *_language_note(stats)]}

    pct = stats["sentimentPercent"]
    lead = max(("positive", "neutral", "negative"), key=lambda s: pct[s])
    overview = (f"Across {total} reviews, {pct['positive']}% read as positive, "
                f"{pct['negative']}% as negative and {pct['neutral']}% as neutral, "
                f"so the overall tone is mostly {lead}.")
    if stats["averageRating"] is not None:
        overview += (f" The average star rating is {stats['averageRating']:.1f} out of 5 "
                     f"from {stats['ratedReviews']} rated reviews.")

    decided = [a for a in aspects if a["verdict"] != "insufficient"]
    strengths = [_aspect_line(a, "positive") for a in decided if a["verdict"] == "positive"]
    complaints = [_aspect_line(a, "negative") for a in decided if a["verdict"] == "negative"]
    mixed = [_aspect_line(a, "negative") for a in decided if a["verdict"] == "mixed"]

    notes = _language_note(stats)
    mismatches = len(stats["ratingSentimentMismatches"])
    if mismatches:
        noun, verb = ("review", "has") if mismatches == 1 else ("reviews", "have")
        notes.append(f"{mismatches} {noun} {verb} a star rating that disagrees with the tone of the text. "
                     "They are flagged in the review list.")
    if total < 30:
        notes.append(f"This summary is based on a small sample of {total} reviews; treat percentages with caution.")
    return {"overview": overview, "strengths": strengths, "complaints": complaints, "mixed": mixed, "notes": notes}
