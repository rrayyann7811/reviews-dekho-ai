"""Evidence-backed summary (summary version 2).

Every sentence is built from computed numbers and exact excerpts of stored
reviews. Nothing here is generated by a language model, so it cannot invent
features, opinions, counts or quotes.

Each claim about a feature keeps its evidence:
* the statement shown to the user;
* the exact counts behind it: how many analysed reviews mention the feature
  (`mentions`) and how many of those read as positive / neutral / negative;
* up to three excerpts, each an exact substring of a stored review's text or
  title, with the review ID.

Counting rule: a review counts once per feature it mentions, so a feature's
`mentions` is a number of reviews, and feature counts do not add up to the
number of reviews (one review can mention several features).

Version 1 (Phases 1-5) had the same claims with one example each and no
statement or evidence list. Stored runs keep the version they were made with.
"""
from .preprocess import dedupe_key

SUMMARY_VERSION = 2
MIN_REVIEWS_FOR_SUMMARY = 5
MAX_EXCERPTS = 3
MAX_EXCERPT_CHARS = 280      # longer excerpts are only used if nothing shorter exists
NEAR_DUPLICATE = 0.7         # word overlap (Jaccard) at which two excerpts count as the same


def _language_note(stats: dict) -> list[str]:
    skipped = (stats.get("notAnalysed") or {}).get("languageNotSupported", 0)
    if not skipped:
        return []
    noun, verb = ("review", "is") if skipped == 1 else ("reviews", "are")
    return [f"{skipped} {noun} {verb} not in English (for example Hindi or Hinglish), so their sentiment wasn’t "
            "analysed. They are left out of the percentages; their star ratings still count."]


# ---------- Evidence ----------

def _exact_excerpt(snippet: str, review: dict) -> tuple[str, str] | None:
    """(excerpt, field) if the snippet appears verbatim in the stored text or title, else None.

    Snippets come from the text the engine analysed, which may differ from the stored text (the title
    added to very short reviews, repeated punctuation shortened). Only exact matches are used as evidence.
    """
    for field in ("text", "title"):
        value = review.get(field) or ""
        if snippet and snippet in value:
            return snippet, field
    return None


def _words(text: str) -> set[str]:
    return set(dedupe_key(text).split())


def _is_near_duplicate(text: str, chosen: list[dict]) -> bool:
    words = _words(text)
    for other in chosen:
        other_words = _words(other["text"])
        union = words | other_words
        if not union or len(words & other_words) / len(union) >= NEAR_DUPLICATE:
            return True
    return False


def _candidates(aspect: str, sentiment: str, reviews: list[dict]) -> list[dict]:
    """Every exact excerpt for this feature and sentiment, strongest first, then by review ID (deterministic)."""
    found = []
    for review in reviews:
        if review.get("status", "analysed") != "analysed" or review.get("sentiment") is None:
            continue  # never quote reviews that weren't analysed (e.g. not in English)
        for mention in review.get("aspects") or []:
            if mention["aspect"] != aspect or mention["sentiment"] != sentiment:
                continue
            exact = _exact_excerpt(mention["snippet"], review)
            if exact:
                found.append({"reviewId": review["id"], "text": exact[0], "field": exact[1],
                              "sentiment": sentiment, "score": mention["score"],
                              "rating": review.get("rating"), "date": review.get("date")})
    strongest_first = -1 if sentiment == "positive" else 1
    # Prefer excerpts short enough to read; within that, the clearest opinion first.
    found.sort(key=lambda e: (len(e["text"]) > MAX_EXCERPT_CHARS, strongest_first * e["score"], str(e["reviewId"])))
    return found


def select_evidence(aspect: str, sentiments: list[str], reviews: list[dict], limit: int = MAX_EXCERPTS,
                    quoted_elsewhere: set | None = None) -> list[dict]:
    """Up to `limit` excerpts, taking the sentiments in turn (e.g. negative, positive, negative), no near-duplicates.

    Reviews already quoted for another feature are used only when there is nothing else, so one review
    doesn't appear under several claims when other evidence exists.
    """
    quoted_elsewhere = quoted_elsewhere or set()
    pools = {}
    for sentiment in dict.fromkeys(sentiments):
        found = _candidates(aspect, sentiment, reviews)
        pools[sentiment] = ([e for e in found if e["reviewId"] not in quoted_elsewhere]
                            + [e for e in found if e["reviewId"] in quoted_elsewhere])
    chosen: list[dict] = []
    used_reviews: set = set()
    position = {s: 0 for s in pools}
    while len(chosen) < limit:
        progressed = False
        for sentiment in sentiments:
            pool = pools[sentiment]
            while position[sentiment] < len(pool):
                candidate = pool[position[sentiment]]
                position[sentiment] += 1
                if candidate["reviewId"] in used_reviews or _is_near_duplicate(candidate["text"], chosen):
                    continue
                chosen.append({k: v for k, v in candidate.items() if k != "score"})
                used_reviews.add(candidate["reviewId"])
                progressed = True
                break
            if len(chosen) == limit:
                break
        if not progressed:
            break
    return chosen


# ---------- Claims ----------

def _percent(part: int, whole: int) -> int:
    return round(100 * part / whole) if whole else 0


def _claim(row: dict, kind: str, analysed: int, reviews: list[dict], quoted: set) -> dict:
    n = row["mentions"]
    if kind == "strength":
        count, evidence = row["positive"], select_evidence(row["aspect"], ["positive"], reviews, quoted_elsewhere=quoted)
        statement = (f"{row['aspect']} is mostly praised: {count} of the {n} analysed reviews that mention it read "
                     f"as positive ({_percent(count, n)}%).")
    elif kind == "complaint":
        count, evidence = row["negative"], select_evidence(row["aspect"], ["negative"], reviews, quoted_elsewhere=quoted)
        statement = (f"{row['aspect']} is a common complaint: {count} of the {n} analysed reviews that mention it "
                     f"read as negative ({_percent(count, n)}%).")
    else:
        count, evidence = row["negative"], select_evidence(row["aspect"], ["negative", "positive"], reviews,
                                                           quoted_elsewhere=quoted)
        statement = (f"Opinions on {row['aspect']} are divided: of the {n} analysed reviews that mention it, "
                     f"{row['positive']} read as positive, {row['neutral']} as neutral and {row['negative']} as negative.")
    quoted.update(e["reviewId"] for e in evidence)
    return {
        "aspect": row["aspect"],
        "kind": kind,
        "statement": statement,
        "mentions": n,                     # analysed reviews that mention this feature (a review counts once)
        "count": count,                    # of those, positive (strength) or negative (complaint, mixed)
        "percent": _percent(count, n),
        "positive": row["positive"],
        "neutral": row["neutral"],
        "negative": row["negative"],
        "analysedReviews": analysed,
        "evidence": evidence,
        "example": evidence[0] if evidence else None,   # kept for clients written for version 1
    }


def overall_tone(counts: dict) -> str:
    """The most common sentiment, or "split" when two share the top count (50% / 50% isn't "mostly" anything)."""
    ranked = sorted(("positive", "neutral", "negative"), key=lambda s: -counts[s])
    return "split" if counts[ranked[0]] == counts[ranked[1]] else ranked[0]


def is_majority(counts: dict, tone: str) -> bool:
    """True if `tone` covers more than half the reviews ("mostly" needs a majority, not just the largest share)."""
    return tone in counts and 2 * counts[tone] > sum(counts.values())


def build_summary(stats: dict, aspects: list[dict], reviews: list[dict] | None = None) -> dict:
    """`reviews` are the analysed reviews of the run (with their per-feature snippets), used for evidence."""
    reviews = reviews or []
    analysed = stats.get("analysedReviews", stats["totalReviews"])
    base = {"version": SUMMARY_VERSION, "overview": None, "overviewClaim": None,
            "strengths": [], "complaints": [], "mixed": []}
    if analysed < MIN_REVIEWS_FOR_SUMMARY:
        first = ("No review could be analysed, so there is no summary." if analysed == 0 else
                 f"Only {analysed} review(s) could be analysed. At least {MIN_REVIEWS_FOR_SUMMARY} are needed for a "
                 "meaningful summary.")
        return base | {"notes": [first, *_language_note(stats)]}

    pct, counts = stats["sentimentPercent"], stats["sentimentCounts"]
    lead = overall_tone(counts)
    if lead == "split":
        tone = "so no single tone is in the majority"
    elif is_majority(counts, lead):
        tone = f"so the overall tone is mostly {lead}"
    else:  # largest share but not over half (e.g. 50% / 42% / 8%): "mostly" would overstate it
        tone = f"so {lead} is the most common tone, but not a majority"
    overview = (f"In this sample of {analysed} analysed reviews, {pct['positive']}% read as positive, "
                f"{pct['negative']}% as negative and {pct['neutral']}% as neutral, {tone}.")
    if stats["averageRating"] is not None:
        overview += (f" The average star rating is {stats['averageRating']:.1f} out of 5 "
                     f"from {stats['ratedReviews']} rated reviews.")
    overview_claim = {"statement": overview, "analysedReviews": analysed, "totalReviews": stats["totalReviews"],
                      "sentimentCounts": counts, "sentimentPercent": pct, "averageRating": stats["averageRating"],
                      "ratedReviews": stats["ratedReviews"]}

    decided = [a for a in aspects if a["verdict"] != "insufficient"]
    quoted: set = set()  # reviews already used as evidence, in claim order (deterministic)
    strengths = [_claim(a, "strength", analysed, reviews, quoted) for a in decided if a["verdict"] == "positive"]
    complaints = [_claim(a, "complaint", analysed, reviews, quoted) for a in decided if a["verdict"] == "negative"]
    mixed = [_claim(a, "mixed", analysed, reviews, quoted) for a in decided if a["verdict"] == "mixed"]

    notes = [f"These figures describe the {analysed} analysed reviews in this data, not every customer of the product."]
    notes += _language_note(stats)
    if aspects:
        notes.append("A review can mention several features, so feature counts don’t add up to the number of reviews.")
    mismatches = len(stats["ratingSentimentMismatches"])
    if mismatches:
        noun, verb = ("review", "has") if mismatches == 1 else ("reviews", "have")
        notes.append(f"{mismatches} {noun} {verb} a star rating that disagrees with the tone of the text. "
                     "They are flagged in the review list.")
    if analysed < 30:
        notes.append(f"This is a small sample of {analysed} reviews; treat percentages with caution.")
    return base | {"overview": overview, "overviewClaim": overview_claim, "strengths": strengths,
                   "complaints": complaints, "mixed": mixed, "notes": notes}
