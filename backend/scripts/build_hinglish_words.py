"""Build the language-check word lists from the SentiMix TRAINING split.

Writes app/nlp/data/hinglish_words.txt and app/nlp/data/english_words.txt.

The language check (app/nlp/language.py) flags Hinglish by counting common Hindi
words written in Latin letters. This script finds those words in human-tagged
data instead of guessing them:

1. Read the SentiMix train split (SemEval-2020 Task 9; ~14k Hindi-English tweets in
   which annotators tagged every word as Hin or Eng).
2. Keep words tagged Hin far more often than Eng (at most 20% Eng tags).
3. Remove words that are also ordinary English in product reviews (EXCLUDE).
4. Write the 300 most frequent.

The same tags give an informal-English word list (words tagged Eng at least 80%
of the time, seen at least 3 times). It lets the check recognise everyday English
that isn't in VADER's sentiment dictionary ("getting", "issues", "calls"), so
short, telegraphic English reviews aren't mistaken for another language.

The evaluation (scripts/evaluate_sentiment.py) uses the separate DEV split, so the
reported detection rates are measured on tweets this list was not built from.

Run from backend/:  .venv/bin/python scripts/build_hinglish_words.py
"""
import hashlib
import re
import sys
from collections import Counter
from pathlib import Path

import httpx
from sklearn.feature_extraction.text import ENGLISH_STOP_WORDS

BACKEND = Path(__file__).resolve().parents[1]
SOURCE = BACKEND / "data" / "eval" / "sentimix_train.txt"
URL = ("https://huggingface.co/datasets/RTT1/SentiMix/resolve/205f0391fc1f10320ec3c10708eaa27e88db04c7/"
       "train_14k_split_conll.txt")
SHA256 = "9b1118ad0a3e46a909e0e380bfa289b8fc748f4e7fca24871129e3a22dd36b80"
TARGET = BACKEND / "app" / "nlp" / "data" / "hinglish_words.txt"
ENGLISH_TARGET = BACKEND / "app" / "nlp" / "data" / "english_words.txt"
TOP_N = 300
ENGLISH_TOP_N = 4000
# Tagged Hindi in tweets, but also everyday English (or tech words) in reviews.
EXCLUDE = {"me", "hi", "ha", "main", "log", "par", "pe", "ram", "har", "na", "ab", "ne", "tab", "band", "lie",
           "hum", "fir", "bat", "dil", "hu", "us", "pass", "bus", "fan", "sale", "mile", "ban", "hit", "game",
           "phone", "mobile", "video", "app", "ok", "sir", "bro", "ji", "pro", "jai", "ma", "mere", "hare", "chat",
           "lag", "plz", "ya", "bar", "mat", "ham", "mar", "mil", "jail", "hay", "di", "aa", "bi", "le", "lo", "ja",
           "ga", "din", "ata", "bata", "pak", "bol", "kia", "sari", "baba", "papa", "didi", "hind", "sharma"}


def main() -> int:
    if not SOURCE.exists():
        SOURCE.parent.mkdir(parents=True, exist_ok=True)
        SOURCE.write_bytes(httpx.get(URL, follow_redirects=True, timeout=120).raise_for_status().content)
    content = SOURCE.read_bytes()
    if hashlib.sha256(content).hexdigest() != SHA256:
        print("Checksum mismatch: delete data/eval/sentimix_train.txt and run again.")
        return 1

    hindi, english, previous = Counter(), Counter(), None
    for line in content.decode("utf-8").splitlines():
        parts = line.split("\t")
        if parts[0] == "meta" or len(parts) != 2:
            previous = None
            continue
        token, tag = parts[0].strip().lower(), parts[1].strip()
        is_handle, previous = previous == "@", token
        if is_handle or not re.fullmatch(r"[a-z]{2,}", token):
            continue
        if tag == "Hin":
            hindi[token] += 1
        elif tag == "Eng":
            english[token] += 1

    words = [w for w, count in hindi.most_common()
             if english[w] <= 0.2 * (count + english[w]) and w not in ENGLISH_STOP_WORDS and w not in EXCLUDE]
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("# Common Hindi words in Latin letters, most frequent first.\n"
                      "# Generated by scripts/build_hinglish_words.py from the SentiMix train split. Do not edit.\n"
                      + "\n".join(words[:TOP_N]) + "\n")
    print(f"Wrote {min(TOP_N, len(words))} words to {TARGET.relative_to(BACKEND)}")

    hindi_list = set(words[:TOP_N])
    english_words = [w for w, count in english.most_common()
                     if count >= 3 and hindi[w] <= 0.2 * (count + hindi[w]) and w not in hindi_list][:ENGLISH_TOP_N]
    ENGLISH_TARGET.write_text("# Common informal English words, most frequent first.\n"
                              "# Generated by scripts/build_hinglish_words.py from the SentiMix train split. Do not edit.\n"
                              + "\n".join(english_words) + "\n")
    print(f"Wrote {len(english_words)} words to {ENGLISH_TARGET.relative_to(BACKEND)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
